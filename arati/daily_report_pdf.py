"""PDF rendering for the Daily Sales and Operations Report.

Laid out in HTML and rendered by WeasyPrint, so the table header repeats on
every page, page numbers come from the print engine, and long transaction
lists never clip. Zero values print as ``0.00`` rather than a blank cell, and
negative amounts (refunds) print with a leading minus.
"""

from __future__ import annotations

from html import escape
from pathlib import Path


def _money(value) -> str:
    try:
        return f"{float(value or 0):,.2f}"
    except (TypeError, ValueError):
        return "0.00"


def _escape(value) -> str:
    return escape(str(value if value is not None else ""))


def _style(settings: dict) -> str:
    return """
@page {
  size: A4 portrait;
  margin: 14mm 12mm 16mm 12mm;
  @bottom-center {
    content: "Page " counter(page) " of " counter(pages);
    font-family: "DejaVu Sans", sans-serif;
    font-size: 8pt;
    color: #555;
  }
}
* { box-sizing: border-box; }
body {
  font-family: "DejaVu Sans", sans-serif;
  font-size: 8.4pt;
  color: #111;
  margin: 0;
}
h1 { font-size: 15pt; margin: 0 0 2px; }
h2 {
  font-size: 9.5pt; margin: 14px 0 5px; padding-bottom: 3px;
  border-bottom: 1px solid #999; text-transform: uppercase; letter-spacing: .4px;
}
.sub { color: #555; font-size: 8pt; margin: 0; }
.masthead { display: flex; justify-content: space-between; align-items: flex-start; }
.masthead .brand { font-size: 16pt; font-weight: bold; }
.masthead .brand-sub { color: #555; font-size: 8pt; }
.meta {
  font-size: 7.6pt; color: #444; text-align: right; line-height: 1.5;
}
.meta b { color: #111; }
.rule { border: none; border-top: 1.6px solid #111; margin: 7px 0 10px; }
table { width: 100%; border-collapse: collapse; }
th {
  background: #eee; border: .5px solid #999; padding: 3px 4px; text-align: left;
  font-size: 7.4pt; text-transform: uppercase;
}
td { border: .5px solid #bbb; padding: 2.5px 4px; vertical-align: top; }
td.num, th.num { text-align: right; font-variant-numeric: tabular-nums; }
td.ctr, th.ctr { text-align: center; }
tr.total td { font-weight: bold; background: #f2f2f2; }
.grid { display: flex; gap: 8px; }
.grid > section {
  flex: 1; border: .5px solid #bbb; padding: 5px 7px;
}
.grid h3 {
  margin: 0 0 4px; font-size: 8.4pt; text-transform: uppercase;
  border-bottom: .5px solid #ccc; padding-bottom: 2px;
}
.kv { display: flex; justify-content: space-between; padding: 1px 0; }
.kv span:first-child { color: #444; }
.kv span:last-child { font-variant-numeric: tabular-nums; }
.kv.strong span { font-weight: bold; color: #111; }
.note {
  font-size: 7.4pt; color: #555; border-left: 2px solid #bbb;
  padding-left: 7px; margin-top: 12px;
}
.empty {
  padding: 12px; text-align: center; color: #666; font-style: italic;
  border: .5px dashed #aaa;
}
"""


def _kv(label: str, value: str, strong: bool = False) -> str:
    css = "kv strong" if strong else "kv"
    return f'<div class="{css}"><span>{_escape(label)}</span><span>{_escape(value)}</span></div>'


def _section(title: str, rows: list[tuple[str, str, bool]]) -> str:
    body = "".join(_kv(label, value, strong) for label, value, strong in rows)
    return f"<section><h3>{_escape(title)}</h3>{body}</section>"


def build_daily_pdf(
    path: str | Path,
    figures: dict,
    settings: dict,
    report_id: str = "",
    version: int = 1,
    generated_by: str = "scheduler",
) -> Path:
    """Write the daily report PDF to ``path``."""
    from weasyprint import HTML

    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)

    hotel = settings.get("hotel_name", "Arati Hotel")
    address = ", ".join(
        part
        for part in (
            settings.get("hotel_address1", ""),
            settings.get("hotel_address2", ""),
        )
        if part
    )
    contact = " · ".join(
        part
        for part in (
            settings.get("hotel_phone", ""),
            settings.get("hotel_email", ""),
            settings.get("hotel_website", ""),
        )
        if part
    )
    business_date = figures["business_date"]
    timezone = figures.get("timezone") or "Asia/Kathmandu"
    generated_at = figures.get("generated_at") or ""

    meta_rows = [
        ("Business date", business_date),
        ("Timezone", timezone),
        ("Report ID", report_id or "—"),
        ("Version", str(version)),
        ("Generated by", generated_by),
        ("Generated at", generated_at),
    ]
    meta_html = "".join(
        f'<div><b>{_escape(label)}:</b> {_escape(value)}</div>' for label, value in meta_rows
    )

    currency = settings.get("currency_symbol") or "रु."

    summary_left = _section(
        "Sales",
        [
            ("Gross sales", _money(figures["gross_sales"]), True),
            ("Less discounts", "-" + _money(figures["discount"]), False),
            ("Taxable sales", _money(figures["taxable_sales"]), False),
            ("Taxes (VAT)", _money(figures["taxes"]), False),
            ("Service charge", _money(figures["service_charge"]), False),
            ("Net sales (ex VAT)", _money(figures["net_sales"]), True),
            ("Invoices issued", str(figures["invoice_count"]), False),
        ],
    )
    summary_right = _section(
        "Collections",
        [
            ("Payments received", _money(figures["payments_received"]), True),
            ("Cash collections", _money(figures["cash_collected"]), False),
            ("Non-cash collections", _money(figures["non_cash_collected"]), False),
            ("Refunds & reversals", "-" + _money(figures["refunds"]), False),
            ("Adjustments", _money(figures["adjustments"]), False),
            ("Opening cash", _money(figures["opening_cash"]), False),
            ("Closing cash", _money(figures["closing_cash"]), True),
            ("Outstanding receivables", _money(figures["outstanding"]), True),
        ],
    )
    revenue_rows = [
        ("Room revenue", _money(figures["room_revenue"]), True),
        ("Food & beverage revenue", _money(figures["food_revenue"]), False),
        ("Other service revenue", _money(figures["service_revenue"]), False),
    ]
    occupancy = figures.get("occupancy", {})
    occupancy_rows = [
        ("Sellable rooms", str(occupancy.get("sellable_rooms", 0)), False),
        ("Occupied at end of day", str(occupancy.get("occupied_end_of_day", 0)), False),
        ("Occupied during the day", str(occupancy.get("occupied_across_day", 0)), False),
        ("Occupancy rate", f"{occupancy.get('occupancy_rate', 0):.2f}%", True),
    ]
    summary_bottom = (
        f'<div class="grid">{_section("Revenue by area", revenue_rows)}'
        f'{_section("Room occupancy", occupancy_rows)}</div>'
    )

    # ---------------------------------------------------------- invoice table
    invoice_rows = []
    for invoice in figures["invoices"]:
        lines = "<br/>".join(
            f"{_escape(line['description'])} "
            f"({line['qty']:g} × {_money(line['unit_price'])})"
            for line in invoice["lines"]
        )
        invoice_rows.append(
            "<tr>"
            f"<td>{_escape(invoice['bill_no'])}</td>"
            f"<td>{_escape(invoice['bill_date'])}</td>"
            f"<td>{_escape(invoice['guest_name'] or 'Walk-in guest')}</td>"
            f"<td>{_escape(invoice['cashier'] or '—')}</td>"
            f"<td>{lines}</td>"
            f"<td class='num'>{_money(invoice['subtotal'])}</td>"
            f"<td class='num'>{_money(invoice['discount'])}</td>"
            f"<td class='num'>{_money(invoice['taxable_net'])}</td>"
            f"<td class='num'>{_money(invoice['vat'])}</td>"
            f"<td class='num'>{_money(invoice['total'])}</td>"
            f"<td>{_escape(invoice['payment_method'])}</td>"
            f"<td class='num'>{_money(invoice['collected'])}</td>"
            f"<td class='num'>{_money(invoice['balance'])}</td>"
            f"<td>{_escape(invoice['room_no'] or '—')}"
            f"{(' · ' + str(invoice['nights']) + 'N') if invoice['nights'] else ''}</td>"
            "</tr>"
        )
    if invoice_rows:
        invoice_table = (
            "<table><thead><tr>"
            "<th>Invoice</th><th>Date</th><th>Guest</th><th>Cashier</th>"
            "<th>Description</th><th class='num'>Subtotal</th><th class='num'>Discount</th>"
            "<th class='num'>Taxable</th><th class='num'>Tax</th><th class='num'>Total</th>"
            "<th>Method</th><th class='num'>Collected</th><th class='num'>Balance</th>"
            "<th>Room</th>"
            "</tr></thead><tbody>"
            + "".join(invoice_rows)
            + "<tr class='total'>"
            f"<td colspan='5'>{len(figures['invoices'])} invoice(s)</td>"
            f"<td class='num'>{_money(figures['subtotal'])}</td>"
            f"<td class='num'>{_money(figures['discount'])}</td>"
            f"<td class='num'>{_money(figures['taxable_sales'])}</td>"
            f"<td class='num'>{_money(figures['taxes'])}</td>"
            f"<td class='num'>{_money(figures['gross_sales'])}</td>"
            "<td colspan='2'></td>"
            f"<td class='num'>{_money(figures['payments_received'])}</td>"
            f"<td class='num'>{_money(figures['outstanding'])}</td>"
            "<td></td></tr>"
            "</tbody></table>"
        )
    else:
        invoice_table = (
            '<div class="empty">No transactions recorded for this business day.</div>'
        )

    # --------------------------------------------------------- payment table
    payment_rows = [
        "<tr>"
        f"<td>{_escape(payment['paid_at'])}</td>"
        f"<td>{_escape(payment['bill_no'])}</td>"
        f"<td>{_escape(payment['guest_name'] or '—')}</td>"
        f"<td>{_escape(payment['method'])}</td>"
        f"<td class='num'>{_money(payment['amount'])}</td>"
        f"<td>{_escape(payment['cashier'] or '—')}</td>"
        f"<td>{_escape(payment['note'] or '')}</td>"
        "</tr>"
        for payment in figures["payments"]
    ]
    if payment_rows:
        payment_table = (
            "<table><thead><tr>"
            "<th>Received at</th><th>Invoice</th><th>Guest</th><th>Method</th>"
            "<th class='num'>Amount</th><th>Cashier</th><th>Note</th>"
            "</tr></thead><tbody>"
            + "".join(payment_rows)
            + f"<tr class='total'><td colspan='4'>{len(figures['payments'])} payment(s)"
            f"</td><td class='num'>{_money(figures['payments_received'])}</td>"
            "<td colspan='2'></td></tr></tbody></table>"
        )
    else:
        payment_table = (
            '<div class="empty">No payments were received on this business day.</div>'
        )

    # ---------------------------------------------------------- refund table
    refund_rows = [
        "<tr>"
        f"<td>{_escape(refund['refunded_at'])}</td>"
        f"<td>{_escape(refund['bill_no'])}</td>"
        f"<td class='ctr'>{_escape(refund['kind'])}</td>"
        f"<td>{_escape(refund['method'])}</td>"
        f"<td class='num'>{_money(refund['amount'])}</td>"
        f"<td>{_escape(refund['reason'] or '—')}</td>"
        "</tr>"
        for refund in figures["refund_rows"]
    ]
    if refund_rows:
        refund_table = (
            "<table><thead><tr>"
            "<th>When</th><th>Invoice</th><th class='ctr'>Type</th><th>Method</th>"
            "<th class='num'>Amount</th><th>Reason</th>"
            "</tr></thead><tbody>"
            + "".join(refund_rows)
            + f"<tr class='total'><td colspan='4'>Refunds and adjustments</td>"
            f"<td class='num'>{_money(figures['refunds'])}</td><td></td></tr>"
            "</tbody></table>"
        )
    else:
        refund_table = (
            '<div class="empty">No refunds or adjustments were recorded.</div>'
        )

    # --------------------------------------------------------- method table
    received = float(figures["payments_received"] or 0)
    method_rows = []
    for entry in figures["by_method"]:
        share = (float(entry["total"]) / received * 100) if received else 0.0
        method_rows.append(
            "<tr>"
            f"<td>{_escape(entry['method'])}</td>"
            f"<td class='num'>{entry['entries']}</td>"
            f"<td class='num'>{_money(entry['total'])}</td>"
            f"<td class='num'>{share:.2f}</td>"
            "</tr>"
        )
    method_table = (
        "<table><thead><tr><th>Payment method</th><th class='num'>Entries</th>"
        "<th class='num'>Collected</th><th class='num'>Share %</th>"
        "</tr></thead><tbody>"
        + ("".join(method_rows) or '<tr><td colspan="4">No collections.</td></tr>')
        + f"<tr class='total'><td>Total</td>"
        f"<td class='num'>{sum(entry['entries'] for entry in figures['by_method'])}</td>"
        f"<td class='num'>{_money(figures['payments_received'])}</td>"
        "<td class='num'>100.00</td></tr></tbody></table>"
    )

    footer_note = (
        f"<p><b>Note on dates.</b> Sales are counted by invoice date, payments by the "
        f"moment the money was received, and refunds by the moment the money went "
        f"back out. A payment received today against an invoice raised earlier is "
        f"counted as a collection today, not as extra sales. All dates use "
        f"{_escape(timezone)}.</p>"
        f"<p><b>Reconciliation.</b> The invoice, payment and refund totals in this "
        f"report were recalculated from the transaction records and matched the "
        f"database before the report was saved.</p>"
    )

    html = f"""<!DOCTYPE html><html><head><meta charset="utf-8">
<title>Daily Sales and Operations Report {business_date}</title>
<style>{_style(settings)}</style></head>
<body data-generated="{_escape(generated_at)}">
<div class="masthead">
  <div>
    <div class="brand">{_escape(hotel)}</div>
    <div class="brand-sub">{_escape(address)}</div>
    <div class="brand-sub">{_escape(contact)}</div>
  </div>
  <div class="meta">{meta_html}</div>
</div>
<hr class="rule">
<h1>Daily Sales and Operations Report</h1>
<p class="sub">Business date {business_date} · {currency} figures · prepared by
{_escape(generated_by)}</p>

<div class="grid">{summary_left}{summary_right}</div>
{summary_bottom}

<h2>Transactions</h2>
{invoice_table}

<h2>Payments received</h2>
{payment_table}

<h2>Refunds and adjustments</h2>
{refund_table}

<h2>Collections by payment method</h2>
{method_table}

<div class="note">{footer_note}</div>
</body></html>"""

    HTML(string=html, base_url=str(path.parent)).write_pdf(str(path))
    return path
